"""mkdocs hooks: build the documentation pages from the README and the source, and publish each page's Markdown next to its HTML.

Nothing under ``docs/`` but ``robots.txt`` is committed. At build time
:func:`site_files` adds the front page (``index.md``, the README), one API
reference page per public module (``reference/<module>.md``, a mkdocstrings
directive that renders the module's docstrings), the reference index, and the
agent-facing ``llms.txt`` and ``llms-full.txt``. Generating them means a new
module or a docstring edit reaches the site without a docs change, and two pull
requests cannot conflict on a generated page.

Agents and tools prefer Markdown to rendered HTML. Every page's Markdown is
written to ``site/<path>.md`` and, for pages served as a directory, to
``site/<path>/index.md`` as well. A reference page's source is only a
mkdocstrings directive, so its Markdown copy is rendered here from the same
docstrings with griffe (which mkdocstrings uses to read them) instead.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any

import griffe

PACKAGE = "inspect_evals_utils"
SITE_URL = "https://inspect-evals-utils.generality.org/"
"""Where docs.yml publishes the site. Must match ``site_url`` in mkdocs.yml (a test checks)."""
REPO_BLOB = "https://github.com/Generality-Labs/inspect-evals-utils/blob/main/"
GENERATED_NOTE = (
    "<!-- Generated by mkdocs_hooks.py at build time; edit the source, not this page. -->"
)

HIDDEN_MEMBER = re.compile(r"^_|^[A-Z]$|^IdT$|^logger$")
"""Module members left out of the reference: private names, TypeVars and loggers.

Keep in step with the mkdocstrings ``filters`` in mkdocs.yml.
"""

_LINK = re.compile(r"\]\(([^)#][^)]*)\)")
_MODULE_BULLET = re.compile(rf"^- `({PACKAGE}\.[\w.]+)`", re.MULTILINE)


def load_package(root: Path) -> griffe.Module:
    """The package as griffe reads it from source, without importing it (the huggingface extra need not be installed)."""
    package = griffe.load(PACKAGE, search_paths=[str(root / "src")], docstring_parser="google")
    assert isinstance(package, griffe.Module)
    return package


def reference_modules(package: griffe.Module) -> list[griffe.Module]:
    """Every public module that gets a reference page, in dotted-name order.

    Packages are skipped: the top-level ``__init__`` only re-exports, and a
    subpackage's modules get pages of their own.
    """
    found: list[griffe.Module] = []

    def walk(module: griffe.Module) -> None:
        for name, child in module.modules.items():
            if name.startswith("_"):
                continue
            if child.modules:
                walk(child)
            else:
                found.append(child)

    walk(package)
    return sorted(found, key=lambda m: m.path)


def page_path(module: griffe.Module) -> str:
    """``reference/readmes/generate.md`` for ``inspect_evals_utils.readmes.generate``."""
    return "reference/" + "/".join(module.path.split(".")[1:]) + ".md"


def summary(obj: griffe.Object) -> str:
    """The first line of an object's docstring, or an empty string."""
    if obj.docstring is None:
        return ""
    return obj.docstring.value.strip().splitlines()[0].strip()


def nav_title(module: griffe.Module) -> str:
    """``readmes.generate`` for ``inspect_evals_utils.readmes.generate``: the sidebar label."""
    return module.path.removeprefix(PACKAGE + ".")


def _front_matter(title: str) -> str:
    return f"---\ntitle: {title}\n---\n\n"


def _without_front_matter(markdown: str) -> str:
    if markdown.startswith("---\n"):
        end = markdown.find("\n---\n", 4)
        if end != -1:
            return markdown[end + len("\n---\n") :].lstrip("\n")
    return markdown


def reference_page(module: griffe.Module) -> str:
    """The page mkdocstrings renders for one module."""
    return (
        _front_matter(nav_title(module))
        + f"# `{module.path}`\n\n{GENERATED_NOTE}\n\n::: {module.path}\n"
    )


def reference_index(modules: list[griffe.Module]) -> str:
    """``reference/index.md``: every module with its one-line summary."""
    lines = [
        "# API reference",
        "",
        GENERATED_NOTE,
        "",
        f"One page per module, rendered from the docstrings. The most-used names are also importable from `{PACKAGE}` itself; `{PACKAGE}.huggingface` is not, so the base package imports without the `huggingface` extra.",
        "",
        "| Module | Summary |",
        "| --- | --- |",
    ]
    for module in modules:
        target = page_path(module).removeprefix("reference/")
        lines.append(f"| [`{module.path}`]({target}) | {summary(module)} |")
    return "\n".join(lines) + "\n"


def site_index(readme: str, docs_dir: Path, modules: list[griffe.Module]) -> str:
    """``index.md``: the README as the front page.

    A module named at the start of a bullet links to its reference page, and
    links to repository files go to GitHub, since the site carries only the docs.
    """
    pages = {m.path: page_path(m) for m in modules}

    def link_module(match: re.Match[str]) -> str:
        name = match.group(1)
        if name in pages:
            return f"- [`{name}`]({pages[name]})"
        return match.group(0)

    def rewrite(match: re.Match[str]) -> str:
        target = match.group(1)
        if target.startswith(("http://", "https://", "mailto:")) or (docs_dir / target).exists():
            return match.group(0)
        if target.startswith("reference/"):
            return match.group(0)
        return f"]({REPO_BLOB}{target})"

    body = _LINK.sub(rewrite, _MODULE_BULLET.sub(link_module, readme))
    first_heading, _, rest = body.partition("\n")
    return f"{first_heading}\n\n{GENERATED_NOTE}\n{rest}"


def _public_members(obj: griffe.Object) -> list[griffe.Object]:
    return [
        member
        for name, member in obj.members.items()
        if isinstance(member, griffe.Object)
        and not HIDDEN_MEMBER.search(name)
        and not name.startswith("__")
    ]


def _signature(function: griffe.Function) -> str:
    params: list[str] = []
    seen_keyword_only = False
    for i, param in enumerate(function.parameters):
        kind = param.kind
        if kind is griffe.ParameterKind.keyword_only and not seen_keyword_only:
            params.append("*")
        if kind in (griffe.ParameterKind.var_positional, griffe.ParameterKind.keyword_only):
            seen_keyword_only = True
        prefix = (
            "*"
            if kind is griffe.ParameterKind.var_positional
            else "**"
            if kind is griffe.ParameterKind.var_keyword
            else ""
        )
        text = prefix + param.name
        if param.annotation is not None:
            text += f": {param.annotation}"
        if param.default is not None and not prefix:
            text += f" = {param.default}" if param.annotation is not None else f"={param.default}"
        params.append(text)
        is_last_positional_only = kind is griffe.ParameterKind.positional_only and (
            i + 1 == len(function.parameters)
            or function.parameters[i + 1].kind is not griffe.ParameterKind.positional_only
        )
        if is_last_positional_only:
            params.append("/")
    if params and params[0] == "self":
        params = params[1:]
    returns = f" -> {function.returns}" if function.returns is not None else ""
    return f"def {function.name}({', '.join(params)}){returns}"


def _declaration(obj: griffe.Object) -> str:
    if isinstance(obj, griffe.Function):
        return _signature(obj)
    if isinstance(obj, griffe.Class):
        bases = f"({', '.join(str(b) for b in obj.bases)})" if obj.bases else ""
        return f"class {obj.name}{bases}"
    if isinstance(obj, griffe.Attribute):
        text = obj.name
        if obj.annotation is not None:
            text += f": {obj.annotation}"
        if obj.value is not None:
            text += f" = {obj.value}"
        return text
    return obj.name


def _render_member(obj: griffe.Object, level: int) -> list[str]:
    lines = [f"{'#' * level} `{obj.name}`", "", "```python", _declaration(obj), "```", ""]
    if obj.docstring is not None:
        lines += [obj.docstring.value.strip(), ""]
    if isinstance(obj, griffe.Class):
        for member in _public_members(obj):
            lines += _render_member(member, level + 1)
    return lines


def module_markdown(module: griffe.Module) -> str:
    """One module's reference as plain Markdown: signatures and raw docstrings."""
    lines = [f"# `{module.path}`", ""]
    if module.docstring is not None:
        lines += [module.docstring.value.strip(), ""]
    for member in _public_members(module):
        if isinstance(member, griffe.Module):
            continue
        lines += _render_member(member, 2)
    return "\n".join(lines).rstrip() + "\n"


def _page_body(markdown: str) -> str:
    return markdown.replace(GENERATED_NOTE + "\n\n", "").replace(GENERATED_NOTE + "\n", "")


def llms_txt(package: griffe.Module, modules: list[griffe.Module]) -> str:
    """``llms.txt`` (https://llmstxt.org): an index an agent can read first, linking to raw Markdown."""
    lines = [
        "# inspect-evals-utils",
        "",
        f"> {summary(package)}",
        "",
        f'Every HTML page on this site is also available as raw Markdown at the same path with a `.md` suffix (for example `{page_path(modules[0])}`). The full documentation is concatenated in `llms-full.txt`. Install with `uv add inspect-evals-utils`, or `uv add "inspect-evals-utils[huggingface]"` for `{PACKAGE}.huggingface`.',
        "",
        "## Overview",
        "",
        f"- [Overview, installation, modules, cache directory, README generation]({SITE_URL}index.md): the README",
        f"- [API reference index]({SITE_URL}reference/index.md): every module with a one-line summary",
        "",
        "## API reference",
        "",
    ]
    for module in modules:
        lines.append(f"- [{module.path}]({SITE_URL}{page_path(module)}): {summary(module)}")
    return "\n".join(lines) + "\n"


def llms_full_txt(index: str | None, modules: list[griffe.Module]) -> str:
    """``llms-full.txt``: the whole documentation in one Markdown file, README first."""
    parts = [_page_body(index)] if index is not None else []
    parts += [module_markdown(m) for m in modules]
    return "\n\n---\n\n".join(p.strip() + "\n" for p in parts)


def site_files(root: Path) -> dict[str, str]:
    """Every page built with the site, by path under ``docs/``."""
    package = load_package(root)
    modules = reference_modules(package)
    readme_path = root / "README.md"
    index = (
        site_index(readme_path.read_text(encoding="utf-8"), root / "docs", modules)
        if readme_path.exists()
        else None
    )
    out: dict[str, str] = {}
    if index is not None:
        out["index.md"] = _front_matter("Overview") + index
    out["reference/index.md"] = reference_index(modules)
    for module in modules:
        out[page_path(module)] = reference_page(module)
    out["llms.txt"] = llms_txt(package, modules)
    out["llms-full.txt"] = llms_full_txt(index, modules)
    return out


def markdown_copies(root: Path) -> dict[str, str]:
    """The Markdown published beside a reference page's HTML, by page path, in place of its directive."""
    return {page_path(m): module_markdown(m) for m in reference_modules(load_package(root))}


_copies: dict[str, str] = {}


def on_files(files: Any, config: Any) -> Any:
    from mkdocs.structure.files import File

    root = Path(config["config_file_path"]).parent
    # Read fresh on every build, so `mkdocs serve` shows a docstring edit without a restart.
    _copies.clear()
    _copies.update(markdown_copies(root))
    for path, content in site_files(root).items():
        committed = files.get_file_from_path(path)
        if committed is not None:
            files.remove(committed)
        files.append(File.generated(config, path, content=content))
    return files


def on_post_page(output: str, page: Any, config: Any) -> str:
    relative = Path(page.file.src_uri)
    content = _copies.get(
        page.file.src_uri, _page_body(_without_front_matter(page.file.content_string))
    )
    site_dir = Path(config["site_dir"])
    targets = [site_dir / relative]
    if relative.name != "index.md":
        targets.append(site_dir / relative.with_suffix("") / "index.md")
    for target in targets:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
    return output
